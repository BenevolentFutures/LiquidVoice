/// Declares a type but never provides its data, like an app that quit after copying.
private final class EmptyDataProvider: NSObject, NSPasteboardItemDataProvider {
    func pasteboard(_: NSPasteboard?, item _: NSPasteboardItem, provideDataForType _: NSPasteboard.PasteboardType) {}
}

// MARK: - Ownership

final class PasteboardOwnershipRegressionTests: XCTestCase {
    func testFailureRestorationPreservesNewerCopy() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.setString("original", forType: .string)
        let manager = SystemPasteboardManager(pasteboard: pasteboard)
        let snapshot = try XCTUnwrap(manager.captureSnapshot())
        XCTAssertTrue(manager.writeTemporaryText("dictation", sessionID: "session"))
        pasteboard.clearContents()
        pasteboard.setString("new user copy", forType: .string)
        XCTAssertFalse(manager.restoreTemporarySnapshot(snapshot, sessionID: "session", expectedText: "dictation"))
        XCTAssertEqual(pasteboard.string(forType: .string), "new user copy")
    }

    func testMatchingMarkersDoNotOverrideNewerClipboardGeneration() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.setString("original", forType: .string)
        let manager = SystemPasteboardManager(pasteboard: pasteboard)
        let snapshot = try XCTUnwrap(manager.captureSnapshot())
        XCTAssertTrue(manager.writeTemporaryText("dictation", sessionID: "session"))
        let temporary = try XCTUnwrap(pasteboard.pasteboardItems?.first)
        let copy = NSPasteboardItem()
        for type in temporary.types {
            try copy.setData(XCTUnwrap(temporary.data(forType: type)), forType: type)
        }
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([copy]))
        XCTAssertFalse(manager.isOwned(sessionID: "session", expectedText: "dictation"))
        XCTAssertFalse(manager.restoreTemporarySnapshot(snapshot, sessionID: "session", expectedText: "dictation"))
        XCTAssertEqual(pasteboard.string(forType: .string), "dictation")
    }

    func testUnchangedTemporaryClipboardCanBeRestored() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.setString("original", forType: .string)
        let manager = SystemPasteboardManager(pasteboard: pasteboard)
        let snapshot = try XCTUnwrap(manager.captureSnapshot())
        XCTAssertTrue(manager.writeTemporaryText("dictation", sessionID: "session"))
        XCTAssertTrue(manager.restoreTemporarySnapshot(snapshot, sessionID: "session", expectedText: "dictation"))
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }
}

// MARK: - Invariant 3: the user's clipboard comes back, and back-to-back pastes queue

final class ClipboardPasteSessionTests: XCTestCase {
    private var pasteboard: NSPasteboard!
    private var session: ClipboardPasteSession!

    override func setUp() {
        super.setUp()
        self.pasteboard = TypingServiceTransientPasteboardTests.makePasteboard()
        self.session = ClipboardPasteSession(
            pasteboard: SystemPasteboardManager(pasteboard: self.pasteboard),
            label: "ClipboardPasteSessionTests"
        )
    }

    override func tearDown() {
        self.session.waitUntilIdle()
        self.pasteboard.releaseGlobally()
        super.tearDown()
    }

    func testPasteOffersTheTranscriptThenRestoresTheOriginalClipboard() throws {
        let customType = NSPasteboard.PasteboardType("com.liquidvoice.tests.custom")
        let item = NSPasteboardItem()
        item.setString("before", forType: .string)
        item.setData(Data([7, 8, 9]), forType: customType)
        XCTAssertTrue(self.pasteboard.writeObjects([item]))

        var textAtDispatch: String?
        let failure = self.session.paste(
            "dictated words",
            dispatch: {
                textAtDispatch = self.pasteboard.string(forType: .string)
                return true
            },
            makeConsumptionWait: { {} }
        )
        XCTAssertNil(failure)
