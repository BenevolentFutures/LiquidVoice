final class TypingServiceTransientPasteboardTests: XCTestCase {
    func testTemporaryPasteboardWriteCarriesText() {
        let pasteboard = Self.makePasteboard()
        defer { pasteboard.releaseGlobally() }

        XCTAssertTrue(SystemPasteboardManager(pasteboard: pasteboard).writeTemporaryText("hello world", sessionID: "session"))
        XCTAssertEqual(pasteboard.string(forType: .string), "hello world")
    }

    func testTemporaryPasteboardWriteIsMarkedForClipboardManagers() throws {
        let pasteboard = Self.makePasteboard()
        defer { pasteboard.releaseGlobally() }

        XCTAssertTrue(SystemPasteboardManager(pasteboard: pasteboard).writeTemporaryText("hello world", sessionID: "session"))
        let item = try XCTUnwrap(pasteboard.pasteboardItems?.first)
        let types = item.types.map(\.rawValue)
        XCTAssertTrue(types.contains(Self.transientType.rawValue), "temporary write must be marked Transient so clipboard managers skip it")
        XCTAssertTrue(types.contains(Self.autoGeneratedType.rawValue), "temporary write must be marked AutoGenerated so clipboard managers skip it")
        XCTAssertEqual(item.data(forType: Self.transientType)?.count, 0)
        XCTAssertEqual(item.data(forType: Self.autoGeneratedType)?.count, 0)
    }

    func testTemporaryPasteboardWriteCarriesSourceAndSession() throws {
        let pasteboard = Self.makePasteboard()
        defer { pasteboard.releaseGlobally() }

        XCTAssertTrue(SystemPasteboardManager(pasteboard: pasteboard).writeTemporaryText("hello world", sessionID: "session"))
        let item = try XCTUnwrap(pasteboard.pasteboardItems?.first)
        XCTAssertEqual(
            item.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")),
            Bundle.main.bundleIdentifier ?? "com.FluidApp.app"
